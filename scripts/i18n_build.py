#!/usr/bin/env python3
"""Build the UI translation files from gateway/src/hub_gateway/i18n_es.py (FTUE #198).

    python3 scripts/i18n_build.py          # write gateway/.../local_ui_static/i18n.js and desktop/ui/i18n.js
    python3 scripts/i18n_build.py --check  # exit 1 if they are out of date (CI / tests)
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "gateway/src/hub_gateway/i18n_es.py"
WEB = ROOT / "gateway/src/hub_gateway/local_ui_static/i18n.js"
DESK = ROOT / "desktop/ui/i18n.js"
WEB_SKIP = ("textarea, input, pre, code, #me-list, #me-detail, #s-detail .t, #fv-text, #fv-list, .imp-item, .me-inote, "
            ".me-note, #nm-view, #pf-text, #g-node, .ap-ev span:last-child")
DESK_SKIP = "textarea, input, pre, code"
ENGINE = r'''"use strict";
// GENERATED by scripts/i18n_build.py from gateway/src/hub_gateway/i18n_es.py: edit those, then run the script.
// Whole app in English or Spanish (FTUE #198): follows the system language; English is the key, so a missing
// translation stays in English. Three tables:
//   EXACT  plain strings (labels, buttons, messages, server errors)
//   PAT    templated strings: {n} a number, {x} {y} {z} any text (translated too when known); in the Spanish
//          side {n:one|many} picks the plural; "(s)" in a key matches an optional plural "s"
//   HTML   whole sentences with inline bold/italics, so Spanish word order reads naturally
// A MutationObserver translates what the screens add later; alert/confirm and API errors go through tr() too.
// User content (notes, skills, files, imports, text fields) is never touched.
(() => {
  const es = /^es\b/i.test(navigator.language || "");
  const EXACT = __EXACT__;
  const PAT = __PAT__;
  const HTML = __HTML__;
  const SKIP = __SKIP__;
  const rx = (s) => s.replace(/[.*+?^$()|[\]\\]/g, "\\$&");
  const COMPILED = Object.entries(PAT).map(([k, v]) => {
    const names = [];
    const src = rx(k).replace(/\\\(s\\\)/g, "s?").replace(/\{([nxyz])\}/g, (_, n) => { names.push(n); return n === "n" ? "(\\d[\\d.,]*)" : "(.+?)"; });
    return { re: new RegExp("^" + src + "$"), names, out: v };
  });
  function render(out, vals) {
    return out.replace(/\{n:([^|}]*)\|([^}]*)\}/g, (_, one, many) => (vals.n === "1" ? one : many))
      .replace(/\{([nxyz])\}/g, (_, n) => (vals[n] ?? ""));
  }
  function tr(s, depth = 0) {
    if (!es || s == null) return s;
    const lead = s.match(/^\s*/)[0], tail = s.match(/\s*$/)[0], k = s.trim();
    if (!k) return s;
    if (EXACT[k]) return lead + EXACT[k] + tail;
    if (depth > 3) return s;
    for (const p of COMPILED) {
      const m = k.match(p.re);
      if (!m) continue;
      const vals = {};
      p.names.forEach((n, i) => { vals[n] = n === "n" ? m[i + 1] : tr(m[i + 1], depth + 1); });
      return lead + render(p.out, vals) + tail;
    }
    for (const sep of [" · ", " — "]) if (k.includes(sep)) {
      const parts = k.split(sep), done = parts.map((x) => tr(x, depth + 1));
      if (done.some((x, i) => x !== parts[i])) return lead + done.join(sep) + tail;
    }
    const sent = k.split(/(?<=[.!?✓]) (?=[A-Z])/);  // several sentences built together: translate each one
    if (sent.length > 1) {
      const done = sent.map((x) => tr(x, depth + 1));
      if (done.some((x, i) => x !== sent[i])) return lead + done.join(" ") + tail;
    }
    return s;
  }
  window.MNEMOS_LANG = es ? "es" : "en";
  window.MNEMOS_I18N = { EXACT, PAT, HTML };
  window.tr = tr;
  window.t = (s) => tr(s);
  const norm = (h) => h.replace(/\s+/g, " ").trim();
  function node(n) {
    const p = n.parentElement;
    if (!p || p.closest(SKIP)) return;
    const v = tr(n.nodeValue);
    if (v !== n.nodeValue) n.nodeValue = v;
  }
  function html(el) {
    if (el.dataset && el.dataset.i18n) return;
    const k = HTML[norm(el.innerHTML)];
    if (k) { el.innerHTML = k; el.dataset.i18n = "1"; }
  }
  function attrs(el) {
    for (const a of ["placeholder", "title"]) { const v = el.getAttribute && el.getAttribute(a); if (v) { const w = tr(v); if (w !== v) el.setAttribute(a, w); } }
  }
  window.applyI18n = (root) => {
    if (!es) return;
    root = root || document.body;
    if (root.nodeType === 3) return node(root);
    if (root.nodeType !== 1 || root.closest(SKIP)) return;
    [root, ...root.querySelectorAll("p, li, summary, span, h3, label")].forEach(html);
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    for (let n = w.nextNode(); n; n = w.nextNode()) node(n);
    attrs(root); root.querySelectorAll("[placeholder], [title]").forEach(attrs);
  };
  if (!es) return;
  const _alert = window.alert.bind(window), _confirm = window.confirm.bind(window);
  window.alert = (m) => _alert(tr(String(m)));
  window.confirm = (m) => _confirm(tr(String(m)));
  document.documentElement.lang = "es";
  document.title = tr(document.title);
  document.addEventListener("DOMContentLoaded", () => {
    window.applyI18n(document.body);
    new MutationObserver((ms) => { for (const m of ms) { if (m.type === "characterData") node(m.target); else m.addedNodes.forEach((x) => window.applyI18n(x)); } })
      .observe(document.body, { childList: true, subtree: true, characterData: true });
  });
})();
'''


def tables():
    spec = importlib.util.spec_from_file_location("i18n_es", SRC)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def render(exact: dict, pat: dict, html: dict, skip: str) -> str:
    d = lambda o: json.dumps(o, ensure_ascii=False, indent=1, sort_keys=True)  # noqa: E731
    return (ENGINE.replace("__EXACT__", d(exact)).replace("__PAT__", d(pat)).replace("__HTML__", d(html))
            .replace("__SKIP__", json.dumps(skip)))


def outputs() -> dict[Path, str]:
    m = tables()
    srv_exact = {k: v for k, v in m.SERVER.items() if "{" not in k}
    srv_pat = {k: v for k, v in m.SERVER.items() if "{" in k}
    return {WEB: render({**m.EXACT, **srv_exact}, {**m.PAT, **srv_pat}, m.HTML, WEB_SKIP),
            DESK: render(m.DESKTOP_EXACT, m.DESKTOP_PAT, {}, DESK_SKIP)}


def main() -> int:
    stale = [p for p, text in outputs().items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if "--check" in sys.argv:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run scripts/i18n_build.py)")
        return 1 if stale else 0
    for p, text in outputs().items():
        p.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
